#!/usr/bin/env python3
"""Generate WiringCraft's app icon in every format the builds need (assets/icon/).

The mark is the one the app draws on its welcome page and menu bar (chrome::logo): a teal
square with a wire running through two nodes, on a 20 x 20 grid. This script is its single
source: it writes the SVG and renders the same geometry to PNG, ICO (Windows) and ICNS
(macOS), so they never drift apart. Needs Pillow. Run from the repository root:

    python tools/gen_icon.py
"""
import os

from PIL import Image, ImageDraw

OUT = os.path.join("assets", "icon")
TEAL = "#0b7f77"  # theme.rs, light theme accent
WHITE = "#ffffff"
GRID = 20.0
RADIUS = 4.5  # corner radius, in grid units
WIRE = [(4, 14), (9, 14), (9, 6), (16, 6)]  # chrome::logo
NODES = [(4, 14), (16, 6)]
NODE_R = 2.0
STROKE = 1.8
PNG_SIZES = [16, 24, 32, 48, 64, 128, 256, 512, 1024]
ICO_SIZES = [16, 24, 32, 48, 64, 128, 256]


def svg() -> str:
    pts = " ".join(f"{x},{y}" for x, y in WIRE)
    nodes = "\n".join(
        f'  <circle cx="{x}" cy="{y}" r="{NODE_R}" fill="{WHITE}"/>' for x, y in NODES
    )
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {GRID:g} {GRID:g}" width="512" height="512">
  <!-- Generated by tools/gen_icon.py; edit that script, not this file. -->
  <rect width="{GRID:g}" height="{GRID:g}" rx="{RADIUS}" fill="{TEAL}"/>
  <polyline points="{pts}" fill="none" stroke="{WHITE}" stroke-width="{STROKE}" stroke-linejoin="miter" stroke-linecap="butt"/>
{nodes}
</svg>
"""


def render(size: int) -> Image.Image:
    # Draw 8x larger and scale down, for smooth edges.
    k = 8
    big = size * k
    s = big / GRID
    img = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    d.rounded_rectangle([0, 0, big - 1, big - 1], radius=RADIUS * s, fill=TEAL)
    for (ax, ay), (bx, by) in zip(WIRE, WIRE[1:]):
        # Square ends half a stroke past each corner, so the bends meet cleanly.
        h = STROKE * s / 2
        x0, x1 = sorted((ax * s, bx * s))
        y0, y1 = sorted((ay * s, by * s))
        if ay == by:
            d.rectangle([x0 - h, y0 - h, x1 + h, y0 + h], fill=WHITE)
        else:
            d.rectangle([x0 - h, y0 - h, x0 + h, y1 + h], fill=WHITE)
    for x, y in NODES:
        r = NODE_R * s
        d.ellipse([x * s - r, y * s - r, x * s + r, y * s + r], fill=WHITE)
    return img.resize((size, size), Image.LANCZOS)


def main() -> None:
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, "wiringcraft.svg"), "w", encoding="utf-8", newline="\n") as f:
        f.write(svg())
    images = {n: render(n) for n in PNG_SIZES}
    for n, img in images.items():
        img.save(os.path.join(OUT, f"wiringcraft-{n}.png"), optimize=True)
    images[256].save(
        os.path.join(OUT, "wiringcraft.ico"), sizes=[(n, n) for n in ICO_SIZES]
    )
    images[1024].save(os.path.join(OUT, "wiringcraft.icns"))
    print(f"wrote {OUT}: svg, {len(PNG_SIZES)} png, ico, icns")


if __name__ == "__main__":
    main()
