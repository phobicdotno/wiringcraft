pub enum Action {
    NewProject,
    Open,
    ProjectProps,
    Save,
    Undo,
    Redo,
    Select,
    PlaceSymbol,
    DrawWire,
    InsertMacro,
    SaveMacro,
    TextTool,
    LineTool,
    RectTool,
    Delete,
    Rotate,
    Mirror,
    Copy,
    Cut,
    Paste,
    SelectAll,
    AddPage,
    DuplicatePage,
    PageProps,
    PageUp,
    PageDown,
    DeletePage,
    NewPanel,
    ArrangePanel,
    DeletePanel,
    ZoomIn,
    ZoomOut,
    ZoomFit,
    ToggleGrid,
    LibraryStatus,
    LibraryUpdate,
    ExportPdf,
    ExportDrawings,
    ExportAml,
    NumberWires,
    Reports,
    Check,
    Commit,
    NewBranch,
    History,
    CommentTool,
    PageHistory,
    ReportProblem,
    RequestFunction,
    ReportMissing,
    ToggleChrome,
    ToggleTheme,
    Assistant,
}

